"""
member1/data_quality_report.py
Generates a comprehensive dataset quality report covering integrity,
missing rates, duplicate rates, image readability, and class distributions.
"""

import sys
import json
from pathlib import Path
from typing import Dict, Any
import pandas as pd
from PIL import Image

# Add project root to sys.path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from config import PROCESSED_DATA_DIR, RESULTS_DIR
from member1.dataset_inspection import inspect_dataframe, validate_image_text_pairs
from member1.label_analysis import analyze_split_distributions


def generate_data_quality_report() -> Dict[str, Any]:
    """Generate and write comprehensive data quality report."""
    train_path = PROCESSED_DATA_DIR / "train.csv"
    val_path = PROCESSED_DATA_DIR / "val.csv"
    test_path = PROCESSED_DATA_DIR / "test.csv"

    if not train_path.exists():
        raise FileNotFoundError("Processed datasets not found. Run dataset_preprocessing.py first.")

    train_df = pd.read_csv(train_path)
    val_df = pd.read_csv(val_path)
    test_df = pd.read_csv(test_path)
    full_df = pd.concat([train_df, val_df, test_df], ignore_index=True)

    # 1. Inspection
    inspection = inspect_dataframe(full_df, "All Clean Data")

    # 2. Pair Validation
    pair_check = validate_image_text_pairs(full_df)

    # 3. Label Analysis
    label_dist = analyze_split_distributions()

    # 4. Text Length Statistics
    lengths = full_df["text"].str.split().str.len()
    text_stats = {
        "min_words": int(lengths.min()),
        "max_words": int(lengths.max()),
        "mean_words": round(float(lengths.mean()), 2),
        "median_words": round(float(lengths.median()), 2)
    }

    report = {
        "report_title": "IndicSent-M Dataset Quality Report",
        "dataset_inspection": inspection,
        "image_text_pair_validation": pair_check,
        "text_statistics": text_stats,
        "label_distributions": label_dist,
        "integrity_status": "PASSED" if pair_check["corrupt_images_count"] == 0 and pair_check["missing_images_count"] == 0 else "WARNING"
    }

    # Save JSON
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    with open(RESULTS_DIR / "data_quality_report.json", "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)

    # Save Markdown summary
    md_content = f"""# IndicSent-M Dataset Quality Report

**Overall Status:** {report['integrity_status']}
**Total Valid Clean Samples:** {report['dataset_inspection']['total_rows']}

## 1. Modality & Pair Health
- **Total Samples Checked:** {pair_check['total_checked']}
- **Valid Text-Image Pairs:** {pair_check['valid_pairs']} ({pair_check['valid_pairs']/pair_check['total_checked']*100:.1f}%)
- **Missing Images:** {pair_check['missing_images_count']}
- **Corrupt Images:** {pair_check['corrupt_images_count']}
- **Missing Texts:** {pair_check['missing_texts_count']}

## 2. Text Statistics
- **Min Words per Caption:** {text_stats['min_words']}
- **Max Words per Caption:** {text_stats['max_words']}
- **Average Word Count:** {text_stats['mean_words']}

## 3. Split Distributions
- **Train Split:** {label_dist.get('train', {}).get('total_samples', 0)} samples
- **Val Split:** {label_dist.get('val', {}).get('total_samples', 0)} samples
- **Test Split:** {label_dist.get('test', {}).get('total_samples', 0)} samples

*Generated by Member 1 (Surya Pratap Singh) module.*
"""
    with open(RESULTS_DIR / "data_quality_report.md", "w", encoding="utf-8") as f:
        f.write(md_content)

    print("Data quality report written to results/data_quality_report.json and .md")
    return report


if __name__ == "__main__":
    generate_data_quality_report()
